package com.hoteluq.domain.loyalty;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;


public final class LoyaltyAccount {
    private final String customerId;
    private final List<PointsLot> lots = new ArrayList<>();
    private final List<LoyaltyEntry> history = new ArrayList<>();

    public LoyaltyAccount(String customerId) {
        if (customerId == null || customerId.isBlank()) {
            throw new LoyaltyException("Customer id is required.");
        }
        this.customerId = customerId.trim();
    }

    /** Adds a lot. Accruing twice for the same reservation is ignored (idempotent). */
    public boolean accrue(String reservationId, int points, LocalDateTime earnedAt) {
        if (points < 1) return false;
        boolean alreadyAccrued = lots.stream()
                .anyMatch(lot -> lot.getReservationId().equals(reservationId));
        if (alreadyAccrued) return false;
        lots.add(new PointsLot(reservationId, points, earnedAt));
        history.add(new LoyaltyEntry(earnedAt, LoyaltyEntry.Kind.EARNED, points,
                "reservation " + reservationId));
        return true;
    }

    public int availablePoints(LocalDateTime now) {
        return lots.stream().mapToInt(lot -> lot.availableAt(now)).sum();
    }

    public void redeem(int points, String detail, LocalDateTime now) {
        if (points < 1) throw new LoyaltyException("Points to redeem must be positive.");
        int available = availablePoints(now);
        if (points > available) throw new InsufficientPointsException(points, available);

        int pending = points;
        List<PointsLot> byExpiry = lots.stream()
                .sorted(Comparator.comparing(PointsLot::getExpiresAt))
                .toList();
        for (PointsLot lot : byExpiry) {
            if (pending == 0) break;
            pending -= lot.consume(pending, now);
        }
        history.add(new LoyaltyEntry(now, LoyaltyEntry.Kind.REDEEMED, points, detail));
    }

    /** Voids what is left of the lot generated by a reservation (used when it is cancelled). */
    public int revoke(String reservationId, LocalDateTime now) {
        int voided = lots.stream()
                .filter(lot -> lot.getReservationId().equals(reservationId))
                .mapToInt(PointsLot::voidRemaining)
                .sum();
        if (voided > 0) {
            history.add(new LoyaltyEntry(now, LoyaltyEntry.Kind.REVERTED, voided,
                    "reservation " + reservationId + " cancelled"));
        }
        return voided;
    }

    public String getCustomerId() { return customerId; }
    public List<PointsLot> getLots() { return List.copyOf(lots); }
    public List<LoyaltyEntry> getHistory() { return List.copyOf(history); }
}